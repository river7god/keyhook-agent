/*
 * Arrears tools (spec §12 R8). Same gateway as maintenance: Zod input, permission level,
 * idempotency key, one audit row per call. The model never sees these — arrears handlers
 * follow "extract → code decides → compose" with no tool loop.
 */

const agent = { type: 'agent' as const };

function hashBody(body: string): string {
  let h = 0;
  for (let i = 0; i < body.length; i++) h = (Math.imul(31, h) + body.charCodeAt(i)) | 0;
  return (h >>> 0).toString(16);
}

export const sendArrearsMessageTool = defineTool({
  name: 'send_arrears_message',
  description: 'Send a message about rent arrears to the tenant (friendly, factual) or the PM.',
  permission: 'auto',
  input: z.strictObject({
    recipient: z.enum(['tenant', 'pm']),
    body: z.string().min(1).max(1500),
  }),
  async run(ctx, input) {
    const c = await getCase(ctx.db, ctx.organizationId, arrearsCaseIdOf(ctx));
    const facts = await loadCaseContext(ctx.db, c);
    const msg = await queueOutbound(ctx.db, {
      organizationId: ctx.organizationId,
      jobId: null,
      arrearsCaseId: c.id,
      recipientType: input.recipient,
      recipientId: input.recipient === 'tenant' ? c.tenantId : facts.propertyManagerId,
      body: input.body,
      idempotencyKey: `${ctx.idempotencyScope}:send_arrears_message:${input.recipient}:${hashBody(input.body)}`,
    });
    return { messageId: msg.id };
  },
});

/** Record what the tenant committed to: a one-off promise or the first instalment of a plan. */
export const recordPromiseTool = defineTool({
  name: 'record_promise',
  description: 'Record a promise to pay, or an agreed payment plan, within policy limits.',
  permission: 'auto',
  input: z.strictObject({
    amountCents: z.number().int().positive(),
    date: z.iso.date(),
    plan: z
      .strictObject({
        instalmentCents: z.number().int().positive(),
        frequency: z.enum(['weekly', 'fortnightly']),
      })
      .nullable(),
  }),
  async run(ctx, input) {
    const caseId = arrearsCaseIdOf(ctx);
    const c = await getCase(ctx.db, ctx.organizationId, caseId);
    const patch = {
      promiseAmountCents: input.amountCents,
      promiseDate: input.date,
      promiseMadeOn: nzDate(ctx.now),
      planInstalmentCents: input.plan?.instalmentCents ?? null,
      planFrequency: input.plan?.frequency ?? null,
    };
    const reason = input.plan
      ? `Payment plan: ${formatNzd(input.plan.instalmentCents)} ${input.plan.frequency}, first on ${input.date}`
      : `Promise to pay ${formatNzd(input.amountCents)} by ${input.date}`;
    const after =
      c.state === 'PROMISED'
        ? await patchCase(ctx.db, { organizationId: ctx.organizationId, caseId, patch, reason })
        : await transitionCase(ctx.db, {
            organizationId: ctx.organizationId,
            caseId,
            to: 'PROMISED',
            actor: agent,
            reason,
            patch,
            now: ctx.now,
          });
    return { state: after.state };
  },
});

/**
 * Draft the 14-day notice to remedy from a fixed template (legal wording is never generated by a
 * model) and ask the PM to approve it. Wording to be checked against Tenancy Services' template.
 */
export function noticeText(args: {
  tenantName: string;
  address: string;
  balanceCents: number;
  oldestUnpaidDate: string;
  remedyBy: string;
}): string {
  return [
    `Notice to remedy: rent arrears — ${args.address}`,
    '',
    `Dear ${args.tenantName},`,
    '',
    `Our records show rent of ${formatNzd(args.balanceCents)} is unpaid, the oldest amount due on ${formatCalendarDate(args.oldestUnpaidDate)}.`,
    `Under the Residential Tenancies Act 1986 you are required to pay this amount by ${formatCalendarDate(args.remedyBy)} (14 days from this notice).`,
    'If the arrears are not paid, the landlord may apply to the Tenancy Tribunal.',
    'If you are having difficulty paying, please contact us — we will work with you.',
  ].join('\n');
}

export const requestNoticeApprovalTool = defineTool({
  name: 'request_notice_approval',
  description: 'Draft the 14-day notice to remedy and send it to the PM for approval.',
  permission: 'auto',
  input: z.strictObject({ reason: z.string().min(3).max(300) }),
  async run(ctx, input) {
    const caseId = arrearsCaseIdOf(ctx);
    const c = await getCase(ctx.db, ctx.organizationId, caseId);
    const facts = await loadCaseContext(ctx.db, c);
    const remedyBy = addDays(nzDate(ctx.now), 14);
    const text = noticeText({
      tenantName: facts.tenantName,
      address: `${facts.address}, ${facts.suburb}`,
      balanceCents: c.balanceCents,
      oldestUnpaidDate: c.oldestUnpaidDate,
      remedyBy,
    });
    const [row] = await ctx.db
      .insert(approvals)
      .values({
        organizationId: ctx.organizationId,
        arrearsCaseId: caseId,
        kind: 'arrears_notice',
        amountCents: c.balanceCents,
        reason: `${input.reason}\n\n${text}`,
        idempotencyKey: `${ctx.idempotencyScope}:request_notice_approval`,
      })
      .onConflictDoNothing()
      .returning({ id: approvals.id });
    await transitionCase(ctx.db, {
      organizationId: ctx.organizationId,
      caseId,
      to: 'NOTICE_PENDING',
      actor: agent,
      reason: input.reason,
      now: ctx.now,
    });
    await queueOutbound(ctx.db, {
      organizationId: ctx.organizationId,
      jobId: null,
      arrearsCaseId: caseId,
      recipientType: 'pm',
      recipientId: facts.propertyManagerId,
      body: `Approval needed: 14-day notice to remedy for ${facts.tenantName} (${facts.address}), ${formatNzd(c.balanceCents)} overdue. ${input.reason}`,
      idempotencyKey: `${ctx.idempotencyScope}:request_notice_approval:pm`,
    });
    return { approvalId: row?.id ?? null };
  },
});

/** Approval-level: only runs after a PM approved the notice (gate in executeTool, rule 2). */
export const sendArrearsNoticeTool = defineTool({
  name: 'send_arrears_notice',
  description: 'Send the approved 14-day notice to remedy to the tenant.',
  permission: 'approval',
  input: z.strictObject({ approvalId: z.uuid() }),
  async run(ctx, input) {
    const caseId = arrearsCaseIdOf(ctx);
    const [a] = await ctx.db
      .select()
      .from(approvals)
      .where(
        and(
          eq(approvals.organizationId, ctx.organizationId),
          eq(approvals.id, input.approvalId),
          eq(approvals.arrearsCaseId, caseId),
          eq(approvals.status, 'approved'),
        ),
      );
    if (!a) throw new DomainError('APPROVAL_REQUIRED', 'No approved notice for this case');
    const c = await getCase(ctx.db, ctx.organizationId, caseId);
    const body = a.reason.slice(a.reason.indexOf('Notice to remedy'));
    await queueOutbound(ctx.db, {
      organizationId: ctx.organizationId,
      jobId: null,
      arrearsCaseId: caseId,
      recipientType: 'tenant',
      recipientId: c.tenantId,
      body,
      idempotencyKey: `${ctx.idempotencyScope}:send_arrears_notice`,
    });
    const after = await transitionCase(ctx.db, {
      organizationId: ctx.organizationId,
      caseId,
      to: 'NOTICE_SENT',
      actor: ctx.actor ?? agent,
      reason: 'PM approved the 14-day notice to remedy',
      patch: { noticeSentAt: ctx.now, remedyByDate: addDays(nzDate(ctx.now), 14) },
      now: ctx.now,
    });
    return { state: after.state };
  },
});

export const escalateArrearsTool = defineTool({
  name: 'escalate_arrears',
  description: 'Hand the arrears case to the PM with a summary and recommendation.',
  permission: 'auto',
  input: z.strictObject({
    reason: z.string().min(3).max(300),
    summary: z.string().min(5).max(1500),
    recommendation: z.string().min(5).max(800),
  }),
  async run(ctx, input) {
    const caseId = arrearsCaseIdOf(ctx);
    const c = await transitionCase(ctx.db, {
      organizationId: ctx.organizationId,
      caseId,
      to: 'ESCALATED',
      actor: agent,
      reason: input.reason,
      patch: { escalationReason: input.reason },
      now: ctx.now,
    });
    const facts = await loadCaseContext(ctx.db, c);
    await queueOutbound(ctx.db, {
      organizationId: ctx.organizationId,
      jobId: null,
      arrearsCaseId: caseId,
      recipientType: 'pm',
      recipientId: facts.propertyManagerId,
      body: `Arrears escalated: ${facts.tenantName}, ${facts.address} — ${formatNzd(c.balanceCents)} overdue since ${c.oldestUnpaidDate}\nWhy: ${input.reason}\n\n${input.summary}\nRecommended: ${input.recommendation}`,
      idempotencyKey: `${ctx.idempotencyScope}:escalate_arrears:pm`,
    });
    await writeAudit(ctx.db, {
      organizationId: ctx.organizationId,
      arrearsCaseId: caseId,
      actorType: 'agent',
      action: 'arrears.escalation_package',
      reason: input.reason,
      output: input,
      outcome: 'ok',
    });
    return { state: c.state };
  },
});
