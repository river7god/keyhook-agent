/**
 * pnpm eval:harvest [--env-file .env.neon.local] [--out evals/scenarios/harvested]
 *
 * Turns PM corrections (agent_feedback rows not yet harvested) into eval scenarios: the job's
 * original tenant/tradie messages become steps, the PM's answer becomes the expectation.
 * Written as `reviewed: false` with basic redaction — a person must review and redact before
 * committing a scenario built from real messages, then set `reviewed: true`.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { and, asc, eq, isNull } from 'drizzle-orm';
import { stringify } from 'yaml';
import { createDb, type Db } from '@/db/client';
import { agentFeedback, jobs, messages, propertyManagers, tenants } from '@/db/schema';
import { PROPERTY } from '@/db/seed/ids';

const here = path.dirname(new URL(import.meta.url).pathname);

export interface HarvestResult {
  written: string[];
  skipped: { feedbackId: string; reason: string }[];
}

/** Mask obvious personal data: emails, phone numbers and the names we know about. */
export function redact(text: string, names: string[]): string {
  let out = text
    .replace(/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, '[email]')
    .replace(/\+?\d[\d\s-]{7,}\d/g, '[phone]');
  for (const n of names
    .flatMap((full) => [full, ...full.split(/\s+/)])
    .filter((n) => n.length > 2)) {
    out = out.replace(
      new RegExp(`\\b${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi'),
      '[name]',
    );
  }
  return out;
}

export async function harvest(db: Db, outDir: string, now = new Date()): Promise<HarvestResult> {
  const result: HarvestResult = { written: [], skipped: [] };
  const propertyKeyById = new Map(Object.entries(PROPERTY).map(([k, v]) => [v, k]));
  const pending = await db
    .select()
    .from(agentFeedback)
    .where(isNull(agentFeedback.harvestedAt))
    .orderBy(asc(agentFeedback.createdAt));

  for (const fb of pending) {
    const [job] = await db
      .select()
      .from(jobs)
      .where(and(eq(jobs.organizationId, fb.organizationId), eq(jobs.id, fb.jobId)));
    if (!job) {
      result.skipped.push({ feedbackId: fb.id, reason: 'job not found' });
      continue;
    }
    const propertyKey = propertyKeyById.get(job.propertyId);
    if (!propertyKey) {
      // Scenarios replay against seed fixtures; a real property has no fixture to stand in for it.
      result.skipped.push({
        feedbackId: fb.id,
        reason: 'property is not a seed fixture — write this scenario by hand',
      });
      continue;
    }
    const inbound = await db
      .select({ senderType: messages.senderType, body: messages.body })
      .from(messages)
      .where(
        and(
          eq(messages.organizationId, fb.organizationId),
          eq(messages.jobId, job.id),
          eq(messages.direction, 'inbound'),
        ),
      )
      .orderBy(asc(messages.createdAt));
    if (!inbound.some((m) => m.senderType === 'tenant')) {
      result.skipped.push({ feedbackId: fb.id, reason: 'job has no tenant messages to replay' });
      continue;
    }
    const [tenant] = job.reportedByTenantId
      ? await db
          .select({ name: tenants.fullName })
          .from(tenants)
          .where(eq(tenants.id, job.reportedByTenantId))
      : [];
    const pms = await db
      .select({ name: propertyManagers.fullName })
      .from(propertyManagers)
      .where(eq(propertyManagers.organizationId, fb.organizationId));
    const names = [tenant?.name, ...pms.map((p) => p.name)].filter((n): n is string => Boolean(n));

    const expect: Record<string, unknown> = {};
    if (fb.expected.urgency) expect.urgency = [fb.expected.urgency];
    if (fb.expected.trade) expect.trade = [fb.expected.trade];
    if (fb.expected.escalate !== undefined) expect.escalate = fb.expected.escalate;
    if (Object.keys(expect).length === 0) {
      result.skipped.push({
        feedbackId: fb.id,
        reason: `"${fb.kind}" has no machine-checkable expectation — write by hand`,
      });
      continue;
    }

    const id = `harvested-${fb.kind.replaceAll('_', '-')}-${fb.id.slice(0, 8)}`;
    const scenario = {
      id,
      description: `PM correction (${fb.source}): agent saw ${JSON.stringify(fb.agentSaw)}${fb.note ? ` — ${redact(fb.note, names)}` : ''}`,
      reviewed: false,
      source: `agent_feedback:${fb.id}`,
      property: propertyKey,
      steps: inbound.map((m) =>
        m.senderType === 'tradie'
          ? { tradie: redact(m.body, names) }
          : { tenant: redact(m.body, names) },
      ),
      expect,
    };
    mkdirSync(outDir, { recursive: true });
    const file = path.join(outDir, `${id}.yaml`);
    writeFileSync(
      file,
      `# Generated by pnpm eval:harvest. REVIEW before committing: check the redaction, then set reviewed: true.\n${stringify(scenario)}`,
    );
    await db.update(agentFeedback).set({ harvestedAt: now }).where(eq(agentFeedback.id, fb.id));
    result.written.push(file);
  }
  return result;
}

async function main() {
  const args = process.argv.slice(2);
  const envIdx = args.indexOf('--env-file');
  const envFile = envIdx >= 0 ? args[envIdx + 1] : '.env';
  const outIdx = args.indexOf('--out');
  const outDir =
    outIdx >= 0 && args[outIdx + 1]
      ? path.resolve(args[outIdx + 1] as string)
      : path.join(here, 'scenarios', 'harvested');
  try {
    process.loadEnvFile(path.resolve(envFile ?? '.env'));
  } catch {
    /* env may come from the shell */
  }
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error('DATABASE_URL is not set');
  const { db, close } = createDb(url, { max: 1 });
  try {
    const r = await harvest(db, outDir);
    for (const f of r.written) console.log(`wrote ${path.relative(process.cwd(), f)}`);
    for (const s of r.skipped) console.log(`skipped ${s.feedbackId}: ${s.reason}`);
    console.log(
      `${r.written.length} scenario(s) written, ${r.skipped.length} skipped. Review, then set reviewed: true.`,
    );
  } finally {
    await close();
  }
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) await main();
